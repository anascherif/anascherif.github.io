// Saves a snapshot of the public repositories to data/repos.js.
// The site reads GitHub live in the browser; this snapshot is what visitors
// see for the first instant, and the fallback if the GitHub API is unreachable.
//
//   node tools/sync-repos.mjs
//
// Runs on a schedule in .github/workflows/deploy.yml. No token is needed for
// public data; GITHUB_TOKEN is used when present to avoid rate limits.
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const USER = process.env.GITHUB_USER || 'anascherif';
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'data', 'repos.js');
const headers = { Accept: 'application/vnd.github+json', 'User-Agent': 'portfolio-sync' };
if (process.env.GITHUB_TOKEN) headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;

const repos = [];
for (let page = 1; page <= 10; page++) {
  const res = await fetch(`https://api.github.com/users/${USER}/repos?per_page=100&sort=pushed&type=owner&page=${page}`, { headers });
  if (!res.ok) throw new Error(`GitHub API answered ${res.status}: ${await res.text()}`);
  const chunk = await res.json();
  for (const r of chunk) {
    repos.push({
      name: r.name, description: r.description, html_url: r.html_url, language: r.language,
      stargazers_count: r.stargazers_count, fork: r.fork, pushed_at: r.pushed_at,
      created_at: r.created_at, archived: r.archived,
    });
  }
  if (chunk.length < 100) break;
}

const body = `// Generated by tools/sync-repos.mjs. Do not edit by hand.\nwindow.REPO_SNAPSHOT = ${JSON.stringify({ fetchedAt: new Date().toISOString(), user: USER, repos }, null, 1)};\n`;
await writeFile(out, body);
console.log(`Saved ${repos.length} repositories to data/repos.js`);
